#!/usr/bin/env bash
#
# Regenerate the repository's `sorry` inventory on stdout.
#
#   scripts/sorry_inventory.sh              # print the inventory
#   scripts/sorry_inventory.sh --check      # compare against the committed file, exit 1 on drift
#
# Why this exists
# ---------------
# `lakefile.toml` sets `warn.sorry = false`, so a `sorry` produces no warning and
# `lake build --wfail` passes. Without this check the repository has no CI signal
# at all when a `sorry` is added. The inventory is committed to
# `scripts/sorry_inventory.txt` so that both additions *and* removals show up as a
# reviewable diff.
#
# Scope: every git-tracked `*.lean` file, repository-wide. Restricting to
# `WeilConjectures/**` is the tempting choice and it is wrong -- it excludes
# `Comparator/Weil/Solution.lean`, the one file where a `sorry` would mean the
# Weil conjectures are not proved.
#
# What counts as a `sorry`
# ------------------------
# The whole identifier `sorry`, after deleting backtick-delimited spans and `--`
# line comments. That deliberately covers tactic positions (`by sorry`,
# `exact sorry`, `· sorry`) that an anchored `^\s*sorry\s*$` regex misses, while
# excluding the repository's very common prose mentions, which are written either
# backticked (`` `sorry` ``) or as the word "sorried".
#
# Block comments are *not* stripped, so an unbackticked prose "sorry" inside a
# docstring will show up here. That direction is deliberate: this check errs
# towards a noisy false positive rather than a silent false negative. If you hit
# one, backtick the word -- every existing docstring in the repository already
# does.
#
# `sorryAx`, `sorried` and `sorry-free` do not match: the identifier must be
# delimited by something that is not an identifier character or a hyphen.

set -euo pipefail

cd "$(dirname "$0")/.."

INVENTORY="scripts/sorry_inventory.txt"

generate() {
  cat <<'HEADER'
# Inventory of `sorry` terms in this repository. Generated by
# `scripts/sorry_inventory.sh`; CI fails if this file and the working tree
# disagree. Regenerate with:
#
#     scripts/sorry_inventory.sh > scripts/sorry_inventory.txt
#
# Convention: the whole identifier `sorry`, in every git-tracked `*.lean` file,
# after deleting backtick-delimited spans and `--` line comments. See the header
# of the script for why the scope is repository-wide and not `WeilConjectures/`.
#
# THE TWO ENTRIES IN `Comparator/Weil/Challenge.lean` ARE CORRECT AND PERMANENT.
# A comparator *challenge* file states its theorems with `sorry` by construction;
# that is the idiom (see `Comparator/README.md`). Do not "fix" them -- doing so
# breaks the challenge/solution pair.
HEADER
  entries="$(list_entries)"
  printf '#\n# TOTAL: %s entries, of which 2 are permanent (see above).\n' \
    "$(printf '%s' "$entries" | grep -c . || true)"
  # Guard the empty case: `printf '%s\n' ""` would emit a spurious blank line,
  # and an inventory that has finally reached zero should be an empty list.
  if [ -n "$entries" ]; then
    printf '%s\n' "$entries"
  fi
}

list_entries() {
  git ls-files -z --cached --others --exclude-standard '*.lean' | sort -z | while IFS= read -r -d '' f; do
    sed -e 's/`[^`]*`//g' -e 's/--.*$//' -- "$f" \
      | grep -nE '(^|[^A-Za-z0-9_])sorry([^A-Za-z0-9_'"'"'-]|$)' \
      | sed "s|^|$f:|" || true
  done
}

if [ "${1-}" = "--check" ]; then
  if diff -u "$INVENTORY" <(generate); then
    printf 'sorry inventory is up to date (%s entries).\n' \
      "$(grep -cv '^#' "$INVENTORY" || true)"
    exit 0
  fi
  cat >&2 <<'FAIL'

The `sorry` inventory is out of date (`-` lines are in the committed file but not
in the tree, `+` lines are in the tree but not committed).

If you removed a `sorry`: thank you -- run

    scripts/sorry_inventory.sh > scripts/sorry_inventory.txt

and commit the result alongside the proof.

If you added one: the same command updates the file, but say in the pull request
why the new `sorry` is acceptable. This repository's goal is that the inventory
only ever shrinks.
FAIL
  exit 1
fi

generate
